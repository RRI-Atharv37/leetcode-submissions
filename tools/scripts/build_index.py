"""Regenerate README stats, INDEX.md and TOPICS.md from data/problems.json + solution headers.

The title/link/difficulty/tags lines at the top of every solution are also refreshed from
problems.json, so that file is the single source of truth for problem metadata.

Usage:
    python tools/scripts/build_index.py          # write generated files
    python tools/scripts/build_index.py --check  # exit 1 if generated files are out of date
"""
from __future__ import annotations

import re
import sys
from collections import Counter, defaultdict
from urllib.parse import quote

import leet
from leet import DIFF_EMOJI, DIFFICULTIES, LANGS, NOTES, ROOT

BANNER = "> 🤖 Generated by `tools/scripts/build_index.py` — don't edit by hand."
BUCKET = 500  # problems per INDEX.md section
RECENT = 5
TOP_TOPICS = 6


def bucket_start(n: int) -> int:
    return ((n - 1) // BUCKET) * BUCKET + 1


def lang_cell(subs) -> str:
    # links are written for files inside docs/, hence the "../"
    if not subs:
        return "–"
    if len(subs) == 1:
        return f"[✓](../{subs[0].path})"
    return " ".join(f"[v{s.version}](../{s.path})" for s in subs)


def note_for(number: int) -> str | None:
    """Note file for a problem, as a path relative to docs/."""
    found = sorted(NOTES.glob(f"{number:04d}-*.md"))
    return found[0].relative_to(ROOT / "docs").as_posix() if found else None


def replace_block(text: str, name: str, content: str) -> str:
    pat = re.compile(rf"(<!-- {name}:START -->)(.*?)(<!-- {name}:END -->)", re.DOTALL)
    if not pat.search(text):
        raise SystemExit(f"README.md is missing the <!-- {name}:START/END --> markers")
    return pat.sub(lambda m: f"{m.group(1)}\n{content}\n{m.group(3)}", text)


def badge(label: str, value, color: str, logo: str = "") -> str:
    # shields.io static badge: '-' and '_' in text must be doubled, everything else URL-encoded
    enc = quote(label.replace("-", "--").replace("_", "__"), safe="")
    extra = f"&logo={logo}&logoColor=white" if logo else ""
    return f"![{label}: {value}](https://img.shields.io/badge/{enc}-{value}-{color}?style=flat-square{extra})"


def generate() -> dict[str, str]:
    problems = leet.load_problems()
    subs, errors = leet.scan(problems)
    if errors:
        leet.fail(errors)

    by_num: dict[int, dict[str, list]] = defaultdict(lambda: defaultdict(list))
    for s in subs:
        by_num[s.number][s.lang].append(s)
    solved = sorted(by_num)
    unsolved = sorted(set(problems) - set(solved))
    if unsolved:
        print("Note: in problems.json but no solution file:", ", ".join(map(str, unsolved)))

    diff_count = Counter(problems[n].difficulty for n in solved)
    lang_problems = Counter(lang for n in solved for lang in by_num[n])
    lang_subs = Counter(s.lang for s in subs)
    tag_count = Counter(t for n in solved for t in problems[n].tags)

    # ---- badges -----------------------------------------------------------
    badges = " ".join([
        badge("Solved", len(solved), "blue"),
        badge("Easy", diff_count["Easy"], "brightgreen"),
        badge("Medium", diff_count["Medium"], "orange"),
        badge("Hard", diff_count["Hard"], "red"),
        badge("C++", lang_problems["cpp"], "00599C", "cplusplus"),
        badge("Python", lang_problems["python"], "3776AB", "python"),
    ])

    # ---- README stats -----------------------------------------------------
    lines = ["## 📊 Progress", "", "| Difficulty | Solved |", "|---|---:|"]
    lines += [f"| {DIFF_EMOJI[d]} {d} | {diff_count[d]} |" for d in DIFFICULTIES]
    lines += ["", "| Language | Problems | Submissions |", "|---|---:|---:|"]
    lines += [f"| {info['name']} | {lang_problems[k]} | {lang_subs[k]} |" for k, info in LANGS.items()]
    if tag_count:
        top = sorted(tag_count.items(), key=lambda kv: (-kv[1], kv[0]))[:TOP_TOPICS]
        lines += ["", "**Top topics:** " + " · ".join(f"`{t}` ({c})" for t, c in top)
                  + " — [all topics](docs/TOPICS.md)"]

    latest: dict[int, leet.Submission] = {}  # newest submission per problem
    for s in subs:
        if s.number not in latest or (s.date or "") >= (latest[s.number].date or ""):
            latest[s.number] = s
    recent = sorted(latest.values(), key=lambda s: (s.date or "", s.number), reverse=True)[:RECENT]
    lines += ["", "### 🕒 Recent", "", "| Date | Problem | Lang |", "|---|---|---|"]
    for s in recent:
        p = problems[s.number]
        langs = " + ".join(LANGS[lang]["name"] for lang in LANGS if by_num[s.number].get(lang))
        lines.append(f"| {leet.pretty_date(s.date)} | [{p.number}. {p.title}]({p.url}) | {langs} |")
    stats = "\n".join(lines)

    readme = (ROOT / "README.md").read_text(encoding="utf-8").replace("\r\n", "\n")
    readme = replace_block(readme, "BADGES", badges)
    readme = replace_block(readme, "STATS", stats)
    if not readme.endswith("\n"):
        readme += "\n"

    # ---- INDEX.md ---------------------------------------------------------
    out = ["# 📚 Problem Index", "", BANNER, "", "[← Back to README](../README.md) · [By topic](TOPICS.md)"]
    current = None
    for n in solved:
        p = problems[n]
        start = bucket_start(n)
        if start != current:
            current = start
            out += ["", f"## {start:04d} – {start + BUCKET - 1:04d}", "",
                    "| # | Problem | Difficulty | C++ | Python | Topics |",
                    "|--:|---|:-:|:-:|:-:|---|"]
        note = note_for(n)
        title = f"[{p.title}]({p.url})" + (f" [📝]({note})" if note else "")
        topics = " ".join(f"`{t}`" for t in p.tags)
        out.append(
            f"| {n} | {title} | {DIFF_EMOJI[p.difficulty]} {p.difficulty} | "
            f"{lang_cell(by_num[n].get('cpp', []))} | {lang_cell(by_num[n].get('python', []))} | {topics} |"
        )
    index = "\n".join(out) + "\n"

    # ---- TOPICS.md --------------------------------------------------------
    by_tag: dict[str, list[int]] = defaultdict(list)
    for n in solved:
        for t in problems[n].tags:
            by_tag[t].append(n)
    out = ["# 🏷️ Problems by Topic", "", BANNER, "", "[← Back to README](../README.md) · [Full index](INDEX.md)", "",
           " · ".join(f"[`{t}`](#{t}) ({len(by_tag[t])})" for t in sorted(by_tag))]
    for t in sorted(by_tag):
        out += ["", f"## {t}", ""]
        for n in by_tag[t]:
            p = problems[n]
            links = []
            for lang, info in LANGS.items():
                group = by_num[n].get(lang, [])
                if len(group) == 1:
                    links.append(f"[{info['name']}](../{group[0].path})")
                else:
                    links += [f"[{info['name']} v{s.version}](../{s.path})" for s in group]
            out.append(f"- [{n}. {p.title}]({p.url}) {DIFF_EMOJI[p.difficulty]} — " + " · ".join(links))
    topics_md = "\n".join(out) + "\n"

    outputs = {"README.md": readme, "docs/INDEX.md": index, "docs/TOPICS.md": topics_md}

    # ---- solution headers -------------------------------------------------
    for s in subs:
        text = (ROOT / s.path).read_text(encoding="utf-8")
        synced = leet.sync_header(text, problems[s.number], s.lang)
        if synced is not None and synced != text.replace("\r\n", "\n"):
            outputs[s.path] = synced
    return outputs


def main(argv: list[str]) -> int:
    check = "--check" in argv
    outputs = generate()
    stale = []
    for name, content in outputs.items():
        path = ROOT / name
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current != content:
            stale.append(name)
            if not check:
                path.write_text(content, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Out of date:", ", ".join(stale), "- run: python tools/scripts/build_index.py")
            return 1
        print("Generated files are up to date.")
        return 0
    print("Updated:", ", ".join(stale) if stale else "nothing (already up to date)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
